    /**
     * Método chamado para pegar os dados da tela e preencher o DTO. Chamado
     * quando o Controller quer salvar os dados.
     */
    @Override
    public InterfaceDTO getDados() {
        ProdutoDTO produtoDTO = dto; // Usa o DTO atual

        produtoDTO.nome = jtfNome.getText(); // Pega o texto do campo Nome
        produtoDTO.valorUnitario = jtfValorUnitario.getText(); // Pega o texto do campo Valor Unitário

        return produtoDTO; // Retorna o DTO preenchido
    }

    /**
     * Método chamado para preencher a tela com dados do DTO. Chamado quando o
     * Controller quer exibir um registro existente.
     */
    @Override
    public void setDTO(InterfaceDTO dto) {
        this.dto = (ProdutoDTO) dto; // Faz cast para ProdutoDTO

        jtfNome.setText(this.dto.nome); // Coloca Nome na tela
        jtfValorUnitario.setText(this.dto.valorUnitario); // Coloca Valor Unitário na tela
    }


